function classifyWorkflowRule(rule: V1474WorkflowRule): V1474WorkflowRule {
  const codeHints = WORKFLOW_STANDARD_WORK_CODE_HINTS[rule.stableCode] ?? {}
  const standardWorkCodes = Array.from(new Set([
    ...(codeHints.predecessorStandardWorkCodes ?? []),
    ...(codeHints.successorStandardWorkCodes ?? []),
  ]))
  const common = {
    ...rule,
    ...codeHints,
    standardWorkCodes,
    defaultLagDays: 0,
    runtimeRole: 'recognition_signal' as const,
    keywordFallbackOnly: true,
    canCreateDependencies: false as const,
  }
  if (WORKFLOW_INTERNAL_FLOW_CANDIDATE_CODES.has(rule.stableCode)) {
    return {
      ...common,
      relationshipScope: 'internal_flow_candidate',
      governanceTarget: 'standard_internal_flow',
      migrationTarget: 'standard_internal_flow',
      boundaryRationale: '同一施工包 / 同一父级内部顺序应迁入 v1.4.7.2 内部流，不得自动作为跨施工包依赖生效。',
      isActive: false,
    }
  }
  if (WORKFLOW_AMBIGUOUS_REVIEW_CODES.has(rule.stableCode)) {
    return {
      ...common,
      relationshipScope: 'ambiguous_review',
      governanceTarget: 'manual_review',
      migrationTarget: 'manual_review',
      boundaryRationale: '该关系需结合 standard_work_code 父级归属判断是内部流还是跨施工包依赖；分类完成前只保留为治理候选。',
      isActive: false,
    }
  }
  if (WORKFLOW_CROSS_ITEM_PROMOTION_CODES.has(rule.stableCode)) {
    return {
      ...common,
      relationshipScope: 'cross_work_package',
      governanceTarget: 'cross_item_workflow',
      migrationTarget: 'cross_item_workflow',
      boundaryRationale: '稳定施工包级移交应升级到 cross_item_workflow；workflow_dictionary 只保留识别信号和兜底解释。',
      isActive: true,
    }
  }
  return {
    ...common,
    relationshipScope: 'unclassified_signal',
    governanceTarget: 'workflow_dictionary',
    migrationTarget: 'workflow_dictionary',
    boundaryRationale: '未分类弱关系信号仅留在 workflow_dictionary 做后台治理；必须先升级到 standard_internal_flow、cross_item_workflow 或 dependencyIntentTemplates 后才可影响运行期关系。',
    isActive: true,
  }
}

