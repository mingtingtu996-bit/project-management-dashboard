const commonRequirements = (itemCode: string, names: string[]): AcceptanceTemplateRequirementSeed[] =>
  names.map((name, index) => ({
    requirementCode: `${itemCode.toUpperCase().replace(/[^A-Z0-9]+/g, '-')}-REQ-${String(index + 1).padStart(2, '0')}`,
    requirementType: 'material',
    sourceEntityType: 'template_material',
    sourceEntityId: `${itemCode}:${index + 1}`,
    description: name,
  }))

const uniqueSeedStrings = (values: string[]) =>
  Array.from(new Set(values.map((value) => value.trim()).filter(Boolean)))

