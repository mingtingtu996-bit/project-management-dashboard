function inferControlChain(record: V1474BuildingPattern): V1474BuildingPatternControlChain {
  const hasAcceptanceGate = record.rhythmDrivers?.includes('acceptance_gate')
  const hasReadinessGate = record.rhythmDrivers?.includes('readiness_gate')
  const hasResourceGate = record.rhythmDrivers?.includes('resource_capacity')
  const gates = unique([
    hasReadinessGate ? 'readiness' : undefined,
    'quality',
    hasAcceptanceGate ? 'acceptance' : undefined,
    hasResourceGate ? 'resource' : undefined,
    record.phaseWindow === 'opening' || record.phaseWindow === 'trial_operation' ? 'operation' : undefined,
    record.phaseWindow === 'handover' || record.phaseWindow === 'opening' ? 'handover' : undefined,
  ].filter(Boolean) as V1474BuildingPatternControlChain['gates'])
  const resultSignal: V1474BuildingPatternControlChain['resultSignal'] =
    record.phaseWindow === 'handover' || record.phaseWindow === 'opening' || record.phaseWindow === 'trial_operation'
      ? 'handover_readiness'
      : record.consumptionPolicy?.baselineGeneration === 'candidate_dependency'
        ? 'candidate_dependency'
        : record.consumptionPolicy?.durationSuggestion === 'floor_curve'
          ? 'duration_context'
          : 'earliest_start'
  return {
    chainCode: `${record.patternCode}_control_chain`,
    steps: inferControlSteps(record),
    gates,
    resultSignal,
  }
}

function inferDurationCurveProfile(record: V1474BuildingPattern, role: V1474BuildingPatternRole): V1474BuildingPatternDurationCurveProfile {
  const positionBasis = inferPositionBasis(record)
  const highReadiness = record.rhythmDrivers?.some((driver) => driver === 'readiness_gate' || driver === 'acceptance_gate') ?? false
  const highResource = record.rhythmDrivers?.includes('resource_capacity') ?? false
  const isFactoryPhase = record.phaseWindow === 'factory'
  return {
    curveCode: `${record.patternCode}_${positionBasis}_curve`,
    positionBasis,
    firstUnitBias: isFactoryPhase ? 'higher' : record.phaseWindow === 'opening' || record.phaseWindow === 'handover' ? 'normal' : 'higher',
    middleUnitBias: record.phaseWindow === 'renovation' || record.phaseWindow === 'foundation' || isFactoryPhase ? 'variable' : 'stable',
    tailUnitBias: highReadiness || record.phaseWindow === 'commissioning' || record.phaseWindow === 'opening' ? 'higher' : 'normal',
    resourceSensitivity: highResource ? 'high' : 'medium',
    readinessSensitivity: highReadiness ? 'high' : role === 'primary_project_mode' ? 'medium' : 'high',
    calibrationPriority: Math.max(1, Math.min(10, Math.round((record.patternPriority ?? inferPatternPriority(role, record)) / 10))),
  }
}

function inferConditionSignals(record: V1474BuildingPattern, mode: 'applicable' | 'exclusion') {
  const source = [
    ...(mode === 'applicable' ? record.applicableConditions ?? [] : record.exclusionConditions ?? []),
    ...(mode === 'applicable' ? record.rhythmDrivers ?? [] : []),
    record.primaryWorkfaceType,
    record.phaseWindow,
  ].join(' ').toLowerCase()
  const signals: string[] = []
  if (source.includes('weather') || source.includes('rain') || source.includes('exterior') || source.includes('roof') || source.includes('facade')) signals.push('weather_window')
  if (source.includes('basement')) signals.push('basement_workface')
  if (source.includes('podium')) signals.push('podium_workface')
  if (source.includes('standard floor') || source.includes('floor_count') || source.includes('standard_floor')) signals.push('standard_floor')
  if (source.includes('roof machine room')) signals.push('roof_machine_room')
  if (source.includes('minor repair')) signals.push('minor_repair_without_exterior_access')
  if (source.includes('single building') || source.includes('single tower')) signals.push('single_building_scope')
  if (source.includes('multiple building') || source.includes('building_count') || source.includes('multi-building')) signals.push('multi_building_scope')
  if (source.includes('shared basement') || source.includes('shared underground')) signals.push('shared_basement_workface')
  if (source.includes('large-span') || source.includes('large public')) signals.push('large_span_public_workface')
  if (source.includes('indoor-only') || source.includes('indoor only')) signals.push('indoor_only')
  if (source.includes('outdoor-only') || source.includes('outdoor only')) signals.push('outdoor_only')
  return unique(signals)
}

function inferNegativeKeywords(record: V1474BuildingPattern) {
  const fromConditions = (record.exclusionConditions ?? [])
    .map((condition) => condition.trim())
    .filter(Boolean)
  const fromSignals = inferConditionSignals(record, 'exclusion')
  return unique([
    ...(record.negativeKeywords ?? []),
    ...fromConditions,
    ...fromSignals,
  ]).slice(0, 12)
}

function buildV1474BuildingPatternDepth(record: V1474BuildingPattern): V1474BuildingPatternEnhancement {
  const classification = V1474_BUILDING_PATTERN_CLASSIFICATION_CONTRACTS[record.patternCode]
  const patternRole = record.patternRole ?? classification?.patternRole ?? inferPatternRole(record)
  const conflictGroup = record.conflictGroup ?? classification?.conflictGroup ?? inferConflictGroup(patternRole, record)
  const coexistsWithGroups: V1474BuildingPatternConflictGroup[] = record.coexistsWithGroups ?? classification?.coexistsWithGroups ?? (
    conflictGroup === 'project_rhythm'
      ? ['phase_rhythm', 'specialty_domain', 'handover_opening']
      : conflictGroup === 'phase_rhythm'
        ? ['project_rhythm', 'specialty_domain', 'handover_opening']
        : ['project_rhythm', 'phase_rhythm']
  )
  return {
    patternRole,
    conflictGroup,
    coexistsWithGroups,
    patternPriority: record.patternPriority ?? classification?.patternPriority ?? inferPatternPriority(patternRole, record),
    controlChains: record.controlChains && record.controlChains.length > 0
      ? record.controlChains
      : [inferControlChain(record)],
    durationCurveProfile: record.durationCurveProfile ?? inferDurationCurveProfile(record, patternRole),
    applicableSignals: record.applicableSignals ?? inferConditionSignals(record, 'applicable'),
    exclusionSignals: record.exclusionSignals ?? inferConditionSignals(record, 'exclusion'),
    calibrationSignals: unique([
      ...(record.calibrationSignals ?? []),
      ...calibrationSignals,
      ...(record.phaseWindow === 'handover' || record.phaseWindow === 'opening' ? ['delay_reason_observation' as const] : []),
    ]),
    selfCalibrationPolicy: 'candidate_overlay_only_no_ts_seed_mutation',
  }
}

